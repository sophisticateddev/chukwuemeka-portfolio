/**
 * The site in English and French. English lives at the normal addresses; French at /fr/…
 * Visitors whose browser asks for French are sent to /fr by middleware.ts, and the
 * EN/FR switch in the nav stores their choice. French copy follows Canadian conventions
 * (no space before ? ! ;) since most French-speaking recruiters he targets are in Canada.
 */
export type Locale = "en" | "fr";

export const LANG_COOKIE = "lang";

export function localeFromPath(pathname: string | null | undefined): Locale {
  return pathname === "/fr" || pathname?.startsWith("/fr/") ? "fr" : "en";
}

/** An internal link in the given language: "/#work" → "/fr#work", "/work/x" → "/fr/work/x". */
export function localeHref(locale: Locale, href: string): string {
  if (locale === "en") return href;
  if (href === "/") return "/fr";
  if (href.startsWith("/#")) return "/fr" + href.slice(1);
  return "/fr" + href;
}

/** The same page in the other language. */
export function switchHref(pathname: string, to: Locale): string {
  const bare = localeFromPath(pathname) === "fr" ? pathname.slice(3) || "/" : pathname;
  return localeHref(to, bare);
}

